import { createRequire } from 'node:module';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';

const require = createRequire(path.join(process.env.TASKLY_RULES_DEPS || process.cwd(), 'package.json'));
const { initializeTestEnvironment, assertFails, assertSucceeds } = require('@firebase/rules-unit-testing');
const { doc, collection, setDoc, getDoc, getDocs, updateDoc, deleteDoc, writeBatch, query, where, setLogLevel } = require('firebase/firestore');
assert.match(process.env.FIRESTORE_EMULATOR_HOST ?? '', /^(127\.0\.0\.1|localhost):\d+$/, 'Local emulator required');
const [host, port] = process.env.FIRESTORE_EMULATOR_HOST.split(':');
const rules = await readFile(new URL('../firestore.rules', import.meta.url), 'utf8');
assert.equal(rules, await readFile(new URL('../../Taskly/firestore.rules', import.meta.url), 'utf8'), 'Both applications must deploy identical rules');
setLogLevel('silent');
const env = await initializeTestEnvironment({ projectId: 'demo-taskly-music', firestore: { host, port: Number(port), rules } });
let checks = 0;
async function allow(operation) { await assertSucceeds(operation); checks++; }
async function deny(operation) { await assertFails(operation); checks++; }
try {
  const alice = env.authenticatedContext('rules-alice').firestore();
  const bob = env.authenticatedContext('rules-bob').firestore();
  const outsider = env.authenticatedContext('rules-outsider').firestore();
  const guest = env.unauthenticatedContext().firestore();
  const chat = 'rules-chat';
  const parent = db => doc(db, 'conversations', chat);
  const message = (db, id) => doc(db, 'conversations', chat, 'messages', id);
  await allow(setDoc(parent(alice), { participantIds: ['rules-alice', 'rules-bob'], createdAt: 1, members: {}, unread: {}, kind: 'dm' }));
  await allow(getDoc(doc(alice, 'conversations', 'rules-missing')));
  await deny(getDoc(parent(outsider)));
  await deny(getDoc(parent(guest)));
  await deny(getDocs(collection(alice, 'conversations')));
  await allow(getDocs(query(collection(alice, 'conversations'), where('participantIds', 'array-contains', 'rules-alice'))));
  await deny(updateDoc(parent(alice), { participantIds: ['rules-alice', 'rules-outsider'] }));
  await deny(updateDoc(parent(alice), { createdAt: 99 }));
  await deny(updateDoc(parent(alice), { 'members.rules-bob': { displayName: 'Impersonation' } }));
  await allow(updateDoc(parent(alice), { 'members.rules-alice': { displayName: 'Alice' } }));
  await allow(setDoc(message(alice, 'one'), { senderId: 'rules-alice', text: 'Original', createdAt: 10 }));
  await allow(updateDoc(message(alice, 'one'), { text: 'Edited', formatting: [{ start: 0, end: 2, style: 'bold' }], edited: true }));
  await deny(updateDoc(message(bob, 'one'), { text: 'Hijacked' }));
  await deny(updateDoc(message(alice, 'one'), { senderId: 'rules-bob' }));
  await allow(updateDoc(message(bob, 'one'), { reactions: { 'rules-bob': 'like' } }));
  await allow(setDoc(message(bob, 'legacy'), { senderId: 'rules-bob', createdAt: 11 }));
  await allow(updateDoc(message(alice, 'legacy'), { reactions: { 'rules-alice': 'like' } }));
  await allow(updateDoc(message(alice, 'legacy'), { replyCount: 1 }));
  await deny(updateDoc(message(alice, 'legacy'), { replyCount: 50 }));
  await allow(updateDoc(message(alice, 'legacy'), { conversationId: chat, searchTerms: ['or'], contentKinds: ['message'] }));
  const files = Array.from({ length: 30 }, (_, index) => ({ name: `${index}.pdf`, kind: 'pdf' }));
  await allow(setDoc(message(alice, 'files'), { senderId: 'rules-alice', createdAt: 12, attachments: files }));
  await deny(setDoc(message(alice, 'too-many'), { senderId: 'rules-alice', createdAt: 12, attachments: [...files, files[0]] }));
  await deny(setDoc(message(alice, 'forged'), { senderId: 'rules-bob', createdAt: 12 }));
  const receipt = (db, uid) => doc(db, 'conversations', chat, 'receipts', uid);
  await allow(getDoc(receipt(alice, 'rules-alice')));
  await allow(setDoc(receipt(alice, 'rules-alice'), { lastReadAt: 10, lastDeliveredAt: 10 }));
  await allow(getDocs(collection(bob, 'conversations', chat, 'receipts')));
  await deny(setDoc(receipt(bob, 'rules-alice'), { lastReadAt: 999 }));
  await deny(getDocs(collection(outsider, 'conversations', chat, 'receipts')));
  const state = (db, uid) => doc(db, 'users', uid, 'chatStates', chat);
  await allow(setDoc(state(bob, 'rules-bob'), { archived: true, archivedAt: 1, pinned: true }));
  await allow(setDoc(state(alice, 'rules-bob'), { archived: false, archivedAt: 0 }, { merge: true }));
  await deny(updateDoc(state(alice, 'rules-bob'), { pinned: false }));
  await deny(updateDoc(state(alice, 'rules-bob'), { archived: true, archivedAt: 2 }));
  await deny(setDoc(state(alice, 'rules-outsider'), { archived: false, archivedAt: 0 }));
  await deny(setDoc(state(outsider, 'rules-bob'), { archived: false, archivedAt: 0 }, { merge: true }));
  const newChat = doc(alice, 'conversations', 'rules-new-chat');
  const creation = writeBatch(alice);
  creation.set(newChat, { participantIds: ['rules-alice', 'rules-bob'], createdAt: 1, kind: 'dm' });
  creation.set(doc(alice, 'conversationSearch', 'rules-new-index'), { userId: 'rules-bob', conversationId: newChat.id, prefixes: ['al'] });
  await allow(creation.commit());
  const index = doc(alice, 'globalChatSearch', 'rules-message-index');
  await allow(setDoc(index, { userId: 'rules-alice', conversationId: chat, messageId: 'one', searchTerms: ['ed'], createdAt: 10 }));
  await allow(getDocs(query(collection(alice, 'globalChatSearch'), where('userId', '==', 'rules-alice'))));
  await deny(getDoc(doc(bob, index.path)));
  await deny(setDoc(doc(alice, 'globalChatSearch', 'rules-forged-index'), { userId: 'rules-outsider', conversationId: chat }));
  await deny(deleteDoc(doc(outsider, index.path)));
  const deletion = writeBatch(bob);
  deletion.delete(message(bob, 'one'));
  deletion.delete(doc(bob, index.path));
  deletion.delete(doc(bob, 'globalChatSearch', 'rules-absent-index'));
  await allow(deletion.commit());
  assert(!(await getDoc(message(alice, 'one'))).exists());
  await deny(deleteDoc(doc(guest, 'globalChatSearch', 'rules-absent-index')));
  const phone = doc(alice, 'phoneIndex', 'rules-phone');
  await allow(setDoc(phone, { uid: 'rules-alice' }));
  await allow(setDoc(phone, { uid: 'rules-alice' }));
  await deny(setDoc(doc(bob, phone.path), { uid: 'rules-bob' }));
  await deny(deleteDoc(doc(bob, phone.path)));
  await allow(setDoc(doc(alice, 'users', 'rules-alice', 'tasks', 'fixture'), { title: 'Private' }));
  await deny(getDoc(doc(bob, 'users', 'rules-alice', 'tasks', 'fixture')));
  const group = doc(alice, 'conversations', 'rules-group');
  await allow(setDoc(group, { participantIds: ['rules-alice', 'rules-bob'], kind: 'group', name: 'Group', createdAt: 1, members: {} }));
  await allow(updateDoc(group, { participantIds: ['rules-alice', 'rules-bob', 'rules-outsider'], 'members.rules-outsider': { displayName: 'Invited' } }));
  await allow(updateDoc(doc(bob, group.path), { participantIds: ['rules-alice', 'rules-outsider'] }));
  console.log(`PASS: ${checks} chat rule checks, rollback, group compatibility, and identical Android/web rules`);
} finally { await env.cleanup(); }
